def test_H15_log_forms_finite_in_deep_tails():
    """logpdf, logcdf and logsf are direct log forms: equal to the log of
    the linear forms where those are representable, and finite where they
    underflow to 0."""
    c, s = 0.4, 0.05
    y = np.array([1e-3, 0.05, 0.2, 0.4, 0.6, 0.9, 0.999])
    for lin, lg in ((bl.pdf, bl.logpdf), (bl.cdf, bl.logcdf),
                    (bl.sf, bl.logsf)):
        with np.errstate(divide='ignore'):        # log(0) is the point
            a = np.log(lin(y, c, s))
        b = lg(y, c, s)
        ok = np.isfinite(a)
        assert np.allclose(a[ok], b[ok], rtol=1e-12, atol=1e-13)
        assert np.all(np.isfinite(b))
    assert bl.pdf(1e-6, c, s) == 0 and np.isfinite(bl.logpdf(1e-6, c, s))
    assert bl.cdf(1e-6, c, s) == 0 and np.isfinite(bl.logcdf(1e-6, c, s))
    assert bl.sf(1 - 1e-6, c, s) == 0 and \
        np.isfinite(bl.logsf(1 - 1e-6, c, s))


