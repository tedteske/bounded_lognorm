def _cid(case):
    return ",".join(str(v) for v in case)


def _rv(case, level='balanced'):
    return bounded_lognorm_gen(precision=level).from_bounds(*case)


def _sigma(case):
    return case[1]


CASES = list(GOLD_POINTS)

EPS = np.finfo(float).eps


def _floor(x, pdf, p):
    """The float64 representation floor, as a relative error in a
    probability p: the input x (or a returned quantile) is only known to
    |x| * eps, which moves p by |x| * eps * pdf. A gold comparison allows
    TOL + 4 * floor, so a case whose x is large relative to its spread
    (such as (950, 1, -1000, 1000)) is held to what float64 can resolve."""
    return np.abs(x) * EPS * pdf / p

# Tolerances, on top of the representation floor (_floor) where one
# applies: set roughly 10x above the worst error measured against the gold
# values over the 15 cases (Nov 2026; worst in the comments), so the suite
# is not flaky but a real regression fails.
TOL_PDF = 3e-11        # relative + floor  worst 3e-12, all at the floor
TOL_CDF = 3e-12        # relative + floor  worst beyond floor: none
TOL_Q_BODY = 3e-12     # rel. err. in q    worst 6e-13 (950-needle, floor)
TOL_Q_TAIL = 3e-12     # rel. err. in q    worst beyond floor: none
TOL_DEEP = 1e-13       # relative in y     worst 6e-15
TOL_RAW = 3e-13        # relative          worst 2e-14
TOL_STATS = 1e-12      # see test_H7       worst 1e-13 (kurtosis)
TOL_ENTROPY = 1e-14    # absolute, nats    worst 9e-16


