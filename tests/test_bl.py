def test_H11_location_scale_equivariance():
    """Moving and stretching the bounds moves and stretches everything."""
    base = (3.0, 1.0, 0.0, 10.0)
    rv0 = bl.from_bounds(*base)
    q = np.array([1e-20, 1e-3, 0.3, 0.5, 0.9, 1 - 1e-9])
    y = np.linspace(0.05, 9.95, 41)
    # (shifts small relative to k * 10, so x itself carries y to ~eps)
    for shift, k in ((-7.0, 1.0), (2.5, 3.0), (-40.0, 25.0), (0.0, 1e-3)):
        m, sg, lo, up = base
        rv = bl.from_bounds(shift + k * m, k * sg, shift + k * lo,
                            shift + k * up)
        x = shift + k * y
        body = rv0.pdf(y) > 1e-30     # deep-tail values amplify rounding of y
        assert np.allclose((rv.pdf(x) * k)[body], rv0.pdf(y)[body],
                           rtol=1e-11, atol=0)
        assert np.allclose(rv.cdf(x)[body], rv0.cdf(y)[body], rtol=1e-11,
                           atol=0)
        assert np.allclose((rv.ppf(q) - shift) / k, rv0.ppf(q),
                           rtol=1e-11, atol=1e-12)
        assert abs(rv.entropy() - rv0.entropy() - np.log(k)) < 1e-12
        assert abs(rv.std() / (k * rv0.std()) - 1) < 1e-12


def test_H12_input_order_and_shape_preserved():
    """The original returned left-of-mode results first for unsorted input
    (Suite I5). Every method now works elementwise."""
    rv = bl.from_bounds(5, 10, -5, 20)
    x = np.array([[9.0, 1.0], [5.0, -4.0], [19.0, 2.0]])
    # (allclose to 1e-14, not bit equality: a vectorized Gauss-Legendre sum
    # may round differently from a one-point one)
    for fn in (rv.pdf, rv.cdf, rv.sf, rv.logpdf):
        out = fn(x)
        assert out.shape == x.shape
        assert np.allclose(out.ravel(), [fn(v) for v in x.ravel()],
                           rtol=1e-14, atol=0)
    q = np.array([0.9, 0.1, 0.5, 1e-12])
    for fn in (rv.ppf, rv.isf):
        assert np.allclose(fn(q), [fn(v) for v in q], rtol=1e-14, atol=0)


def test_H12b_rvs_order_is_the_draw_order():
    """rvs returns draws in the order generated: the closed-form inverse of
    the same uniforms, not grouped by side of the mode as the original
    did. With 2000 draws, the left-of-mode share of each half is near p1."""
    rv = bl.from_bounds(5, 10, -5, 20)
    c, s, loc, scale = bl.bounds_to_shapes(5, 10, -5, 20)
    x = rv.rvs(size=2000, random_state=np.random.default_rng(1))
    u = np.random.default_rng(1).uniform(size=2000)
    y = bl._quantile_closed(u, float(c), float(s), upper_tail=False)
    assert np.allclose(x, loc + scale * y, rtol=0, atol=1e-12)
    p1 = float(rv.cdf(5))
    for half in (x[:1000], x[1000:]):
        assert abs(np.mean(half <= 5) - p1) < 0.06
    # seeded and reproducible (the original used the global np.random)
    assert np.array_equal(rv.rvs(size=5, random_state=7),
                          rv.rvs(size=5, random_state=7))


